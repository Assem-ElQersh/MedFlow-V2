semantic_model = None

ANSWER_SYNONYMS = {
    "not seen here": ["not visible", "absent", "cannot be seen", "not present", "not shown", "not observed"],
    "not visible": ["not seen", "absent", "cannot be seen", "not present", "not shown"],
    "yes": ["present", "visible", "there is", "affirmative", "positive", "confirmed"],
    "no": ["absent", "not present", "none", "negative", "not visible", "not seen"],
    "left": ["left side", "on the left", "leftward"],
    "right": ["right side", "on the right", "rightward"],
    "smaller": ["reduced", "decreased", "diminished"],
    "larger": ["increased", "enlarged", "bigger", "expanded"]
}

def initialize_model():
    global processor, model, semantic_model
    if processor is None or model is None:
        try:
            print("Loading MedGemma-4B-IT model...")
            processor = AutoProcessor.from_pretrained(MODEL_NAME, token=api_key)
            model = AutoModelForImageTextToText.from_pretrained(
                MODEL_NAME,
                token=api_key,
                torch_dtype=torch.bfloat16,
                device_map="auto"
            )
            print("Model loaded successfully!")
        except Exception as e:
            print(f"Error loading model: {e}")
            return False

    if semantic_model is None:
        try:
            print("Loading semantic similarity model...")
            semantic_model = SentenceTransformer('all-MiniLM-L6-v2')
            print("Semantic model loaded!")
        except Exception as e:
            print(f"Error loading semantic model: {e}")
            return False

    return True

initialize_model()

def check_synonyms(prediction, ground_truth):
    """Check if prediction matches any known synonyms of ground truth"""
    pred_lower = prediction.lower().strip()
    gt_lower = ground_truth.lower().strip()

    if pred_lower == gt_lower:
        return True

    if gt_lower in ANSWER_SYNONYMS:
        for synonym in ANSWER_SYNONYMS[gt_lower]:
            if synonym in pred_lower or pred_lower in synonym:
                return True

    if pred_lower in ANSWER_SYNONYMS:
        for synonym in ANSWER_SYNONYMS[pred_lower]:
            if gt_lower in synonym or synonym in gt_lower:
                return True

    return False

def semantic_similarity_score(text1, text2):
    """Calculate semantic similarity between two texts"""
    if semantic_model is None:
        return 0.0

    embeddings = semantic_model.encode([text1, text2])
    similarity = cosine_similarity([embeddings[0]], [embeddings[1]])[0][0]
    return similarity

def extract_answer(text, ground_truth):
    """Extract the actual answer from verbose model output"""
    text_lower = text.lower()
    gt_lower = ground_truth.lower()

    if gt_lower in ["yes", "no"]:
        yes_patterns = [r'\byes\b', r'\bthere is\b', r'\bpresent\b', r'\bvisible\b', r'\baffected\b', r'\bconfirmed\b']
        no_patterns = [r'\bno\b', r'\bnot\b', r'\babsent\b', r'\bnone\b', r'\bno evidence\b', r'\bno obvious\b', r'\bnot visible\b']

        yes_count = sum(1 for p in yes_patterns if re.search(p, text_lower))
        no_count = sum(1 for p in no_patterns if re.search(p, text_lower))

        if yes_count > no_count:
            return "yes"
        elif no_count > yes_count:
            return "no"

    comparatives = ["smaller", "larger", "left", "right", "reduced", "increased", "enlarged"]
    for comp in comparatives:
        if comp in text_lower:
            return comp

    visibility_terms = ["not visible", "not seen", "cannot be seen", "not present", "not shown"]
    for term in visibility_terms:
        if term in text_lower:
            return "not visible"

    if gt_lower in text_lower:
        return ground_truth

    first_sentence = text.split('.')[0].strip()
    return first_sentence

def normalize_answer(text):
    """Normalize answers for comparison"""
    return text.lower().strip().replace(".", "").replace(",", "").replace("the ", "")

def is_answer_correct(prediction, ground_truth):
    """Comprehensive answer matching with multiple strategies"""
    pred_normalized = normalize_answer(prediction)
    gt_normalized = normalize_answer(ground_truth)

    if pred_normalized == gt_normalized:
        return True

    if check_synonyms(prediction, ground_truth):
        return True

    similarity = semantic_similarity_score(prediction, ground_truth)
    if similarity > 0.85:
        return True

    return False

def generate_response(image, question):
    """Generate model response with improved prompting for evaluation"""
    prompt = f"{question}\n\nProvide a concise answer (one word or short phrase preferred)."

    messages = [
        {"role": "system", "content": [{"type": "text", "text": "You are an expert medical assistant. Provide concise, direct answers."}]},
        {"role": "user", "content": [
            {"type": "image", "image": image},
            {"type": "text", "text": prompt}
        ]}
    ]

    inputs = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt"
    ).to(model.device, dtype=torch.bfloat16)

    input_len = inputs["input_ids"].shape[-1]

    with torch.inference_mode():
        generation = model.generate(
            **inputs,
            max_new_tokens=256,
            temperature=0.1,
            do_sample=False
        )
        generation = generation[0][input_len:]

    return processor.decode(generation, skip_special_tokens=True)

