def evaluate_on_dataset(dataset_name, num_samples, progress=gr.Progress()):
    """Evaluate model on medical VQA dataset with advanced matching"""
    if processor is None or model is None:
        return "Model not loaded", None, None

    progress(0, desc="Loading dataset...")

    try:
        # Load appropriate dataset
        if dataset_name == "VQA-RAD (Mixed)":
            dataset, info = load_vqa_rad_dataset()
        elif dataset_name == "SLAKE (Multi-modal)":
            dataset, info = load_slake_dataset()
        elif dataset_name == "PathVQA (Pathology)":
            dataset, info = load_pathvqa_dataset()
        else:
            return f"Dataset {dataset_name} not implemented yet", None, None

        if dataset is None:
            return info, None, None

        num_samples = min(num_samples, len(dataset))
        dataset = dataset.select(range(num_samples))

        results = []
        correct = 0
        total = 0

        for idx, sample in enumerate(dataset):
            progress((idx + 1) / num_samples, desc=f"Evaluating {idx + 1}/{num_samples}")

            image = sample['image']
            question = sample['question']
            ground_truth = sample['answer']

            full_prediction = generate_response(image, question)
            extracted_answer = extract_answer(full_prediction, ground_truth)

            is_correct = is_answer_correct(extracted_answer, ground_truth)
            if is_correct:
                correct += 1
            total += 1

            similarity_score = semantic_similarity_score(extracted_answer, ground_truth)

            results.append({
                'Question': question,
                'Ground Truth': ground_truth,
                'Full Response': full_prediction[:150] + "..." if len(full_prediction) > 150 else full_prediction,
                'Extracted': extracted_answer,
                'Similarity': f"{similarity_score:.2f}",
                'Match': '✓' if is_correct else '✗'
            })

        accuracy = correct / total if total > 0 else 0

        df = pd.DataFrame(results)

        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

        ax1.bar(['Correct', 'Incorrect'],
                [correct, total - correct],
                color=['#4CAF50', '#F44336'],
                edgecolor='black',
                linewidth=1.5)
        ax1.set_ylabel('Count', fontsize=12, fontweight='bold')
        ax1.set_title(f'Accuracy: {accuracy:.1%}', fontsize=14, fontweight='bold')
        ax1.set_ylim(0, max(total, 10))
        ax1.grid(axis='y', alpha=0.3, linestyle='--')

        for i, v in enumerate([correct, total - correct]):
            ax1.text(i, v + 0.3, str(v), ha='center', va='bottom', fontsize=12, fontweight='bold')

        colors = ['#4CAF50', '#F44336']
        explode = (0.05, 0)
        ax2.pie([correct, total - correct],
                labels=['Correct', 'Incorrect'],
                autopct='%1.1f%%',
                colors=colors,
                explode=explode,
                startangle=90,
                textprops={'fontsize': 11, 'fontweight': 'bold'},
                shadow=True)
        ax2.set_title('Result Distribution', fontsize=14, fontweight='bold')

        plt.tight_layout()

        summary = f"""Evaluation Results on {dataset_name}:

Dataset Info: {info}

Samples Evaluated: {total}
Correct Predictions: {correct}
Incorrect Predictions: {total - correct}
Accuracy: {accuracy:.2%}

Matching Strategy:
✓ Exact match normalization
✓ Synonym detection (medical terms)
✓ Semantic similarity (threshold: 0.85)

Note: Advanced matching considers semantic equivalence and medical terminology synonyms."""

        return summary, df, fig

    except Exception as e:
        return f"Error during evaluation: {str(e)}", None, None

def process_medical_case(image, text_input, conversation_history):
    if processor is None or model is None:
        if not initialize_model():
            return "Error: Model not loaded.", []

    is_initial = len(conversation_history) == 0

    messages = []

    if is_initial:
        messages.append({
            "role": "system",
            "content": [{"type": "text", "text": "You are an expert medical assistant."}]
        })

        user_content = []
        if image is not None:
            user_content.append({"type": "image", "image": image})

        if text_input:
            prompt_text = f"""Analyze this medical case and provide an initial diagnosis.

Patient Information:
{text_input}

Please provide:
1. Initial observations
2. Potential diagnosis
3. Recommended next steps for further evaluation"""
        else:
            if image is None:
                return "Please provide either an image, text description, or both.", []
            prompt_text = """Analyze this medical image and provide an initial diagnosis.

Please examine the medical image and provide:
1. Initial observations
2. Potential diagnosis
3. Recommended next steps for further evaluation"""

        user_content.append({"type": "text", "text": prompt_text})
        messages.append({"role": "user", "content": user_content})
    else:
        messages.append({
            "role": "system",
            "content": [{"type": "text", "text": "You are an expert medical assistant."}]
        })

        for entry in conversation_history:
            if entry["role"] == "user":
                messages.append({
                    "role": "user",
                    "content": [{"type": "text", "text": entry["content"]}]
                })
            elif entry["role"] == "assistant":
                messages.append({
                    "role": "assistant",
                    "content": [{"type": "text", "text": entry["content"]}]
                })

        user_content = []
        if image is not None:
            user_content.append({"type": "image", "image": image})
        user_content.append({"type": "text", "text": text_input})
        messages.append({"role": "user", "content": user_content})

    try:
        if image is not None:
            if isinstance(image, str):
                image = Image.open(image)
            elif not isinstance(image, Image.Image):
                image = Image.fromarray(image)

            for msg in messages:
                if msg["role"] == "user":
                    for item in msg["content"]:
                        if item.get("type") == "image":
                            item["image"] = image

        inputs = processor.apply_chat_template(
            messages,
            add_generation_prompt=True,
            tokenize=True,
            return_dict=True,
            return_tensors="pt"
        ).to(model.device, dtype=torch.bfloat16)

        input_len = inputs["input_ids"].shape[-1]

        with torch.inference_mode():
            generation = model.generate(
                **inputs,
                max_new_tokens=512,
                temperature=0.7,
                do_sample=True,
                top_p=0.9
            )
            generation = generation[0][input_len:]

        response = processor.decode(generation, skip_special_tokens=True)

        if is_initial:
            user_content_text = text_input if text_input else "Please analyze this medical case."
            conversation_history = [
                {"role": "user", "content": user_content_text},
                {"role": "assistant", "content": response}
            ]
        else:
            conversation_history.append({"role": "user", "content": text_input})
            conversation_history.append({"role": "assistant", "content": response})

        return response, conversation_history

    except Exception as e:
        error_msg = f"Error: {str(e)}"
        print(error_msg)
        return error_msg, conversation_history

