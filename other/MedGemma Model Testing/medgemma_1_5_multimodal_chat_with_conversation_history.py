"""## 7. Interactive Chat Loop"""

def interactive_chat():
    print("MedGemma Interactive Chat")
    print("Commands:")
    print("  'upload' - Upload an image")
    print("  'stats' - Show session statistics")
    print("  'clear' - Clear chat history")
    print("  'quit' - Exit\n")

    while True:
        user_input = input("You: ").strip()

        if user_input.lower() in ['quit', 'exit']:
            print("Session ended.")
            break

        if user_input.lower() == 'upload':
            uploaded = files.upload()
            if uploaded:
                filename = list(uploaded.keys())[0]
                caption = input("Enter description (or press Enter): ").strip()
                if not caption:
                    caption = "Please analyze this medical image."

                try:
                    response = session.add_message(text=caption, image=filename)
                    print(f"MedGemma: {response}\n")
                except Exception as e:
                    print(f"Error: {e}\n")
            continue

        if user_input.lower() == 'stats':
            print(session.get_history_summary() + "\n")
            continue

        if user_input.lower() == 'clear':
            session.clear_history()
            print("History cleared.\n")
            continue

        if not user_input:
            continue

        try:
            response = session.add_message(text=user_input)
            print(f"MedGemma: {response}\n")
        except Exception as e:
            print(f"Error: {e}\n")

interactive_chat()

