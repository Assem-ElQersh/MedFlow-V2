"""## 9. Advanced: Save/Load Chat History"""

import json
import base64
from io import BytesIO

def save_session(session, filename="chat_history.json"):
    history_serializable = []

    for msg in session.chat_history:
        new_msg = {"role": msg["role"], "content": []}

        for item in msg["content"]:
            if item["type"] == "text":
                new_msg["content"].append(item)
            elif item["type"] == "image":
                buffered = BytesIO()
                item["image"].save(buffered, format="PNG")
                img_str = base64.b64encode(buffered.getvalue()).decode()
                new_msg["content"].append({
                    "type": "image_base64",
                    "data": img_str
                })

        history_serializable.append(new_msg)

    with open(filename, "w") as f:
        json.dump(history_serializable, f)

    print(f"Session saved to {filename}")

def load_session(session, filename="chat_history.json"):
    with open(filename, "r") as f:
        history_serializable = json.load(f)

    session.chat_history = []

    for msg in history_serializable:
        new_msg = {"role": msg["role"], "content": []}

        for item in msg["content"]:
            if item["type"] == "text":
                new_msg["content"].append(item)
            elif item["type"] == "image_base64":
                img_data = base64.b64decode(item["data"])
                img = Image.open(BytesIO(img_data))
                new_msg["content"].append({
                    "type": "image",
                    "image": img
                })

        session.chat_history.append(new_msg)

    print(f"Session loaded from {filename}")

print("Save/Load functions defined")

