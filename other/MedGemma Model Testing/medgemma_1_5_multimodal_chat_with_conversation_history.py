"""## 4. Medical Chat Session Class"""

from PIL import Image
import requests
from io import BytesIO
from typing import List, Dict, Union, Optional
import gc

class MedGemmaChatSession:
    def __init__(
        self,
        model,
        processor,
        max_turns_with_images: int = 3,
        max_new_tokens: int = 512,
        temperature: float = 0.7,
        system_prompt: Optional[str] = None
    ):
        self.model = model
        self.processor = processor
        self.max_turns_with_images = max_turns_with_images
        self.max_new_tokens = max_new_tokens
        self.temperature = temperature

        self.chat_history: List[Dict] = []
        self.image_count = 0

        if system_prompt is None:
            system_prompt = (
                "You are a helpful medical AI assistant. You analyze medical images and text. "
                "Always remind users to consult qualified healthcare professionals for medical decisions."
            )

        self.chat_history.append({
            "role": "system",
            "content": [{"type": "text", "text": system_prompt}]
        })

    def _load_image(self, image_input: Union[str, Image.Image]) -> Image.Image:
        if isinstance(image_input, Image.Image):
            return image_input.convert("RGB")

        if image_input.startswith("http://") or image_input.startswith("https://"):
            response = requests.get(image_input)
            response.raise_for_status()
            return Image.open(BytesIO(response.content)).convert("RGB")
        else:
            return Image.open(image_input).convert("RGB")

    def _manage_memory(self):

        image_turns = sum(
            1 for msg in self.chat_history
            if any(item["type"] == "image" for item in msg.get("content", []))
        )

        while image_turns > self.max_turns_with_images:
            for i in range(1, len(self.chat_history)):
                if any(item["type"] == "image" for item in self.chat_history[i].get("content", [])):
                    self.chat_history.pop(i)
                    image_turns -= 1
                    break

        if torch.cuda.is_available():
            torch.cuda.empty_cache()
        gc.collect()

    def add_message(
        self,
        text: str,
        image: Optional[Union[str, Image.Image]] = None
    ) -> str:
        content = []

        if image is not None:
            try:
                pil_image = self._load_image(image)
                content.append({"type": "image", "image": pil_image})
                self.image_count += 1
            except Exception as e:
                print(f"Warning: Failed to load image: {e}")

        if text:
            content.append({"type": "text", "text": text})

        if not content:
            raise ValueError("Must provide either text or image")

        self.chat_history.append({
            "role": "user",
            "content": content
        })

        try:
            inputs = self.processor.apply_chat_template(
                self.chat_history,
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                return_tensors="pt"
            ).to(self.model.device, dtype=torch.bfloat16)

            input_len = inputs["input_ids"].shape[-1]

            with torch.inference_mode():
                generation = self.model.generate(
                    **inputs,
                    max_new_tokens=self.max_new_tokens,
                    do_sample=True,
                    temperature=self.temperature,
                    pad_token_id=self.processor.tokenizer.pad_token_id
                )

            response_text = self.processor.decode(
                generation[0][input_len:],
                skip_special_tokens=True
            )

            self.chat_history.append({
                "role": "assistant",
                "content": [{"type": "text", "text": response_text}]
            })

            self._manage_memory()

            return response_text

        except Exception as e:
            print(f"Error during generation: {e}")
            self.chat_history.pop()
            raise

    def get_history_summary(self) -> str:
        total_turns = len([m for m in self.chat_history if m["role"] == "user"])
        images_in_history = sum(
            sum(1 for item in msg.get("content", []) if item["type"] == "image")
            for msg in self.chat_history
        )

        return (
            f"Session stats:\n"
            f"- Total turns: {total_turns}\n"
            f"- Images in history: {images_in_history}\n"
            f"- Total images uploaded: {self.image_count}"
        )

    def clear_history(self, keep_system_prompt: bool = True):
        if keep_system_prompt:
            self.chat_history = self.chat_history[:1]
        else:
            self.chat_history = []
        self.image_count = 0
        self._manage_memory()

print("MedGemmaChatSession class loaded successfully!")

