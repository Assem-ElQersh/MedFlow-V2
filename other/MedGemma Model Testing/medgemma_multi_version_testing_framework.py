"""## Connect to MedGemma VLM (Model Loading Function)

### Subtask:
Create a function to securely log in to Hugging Face and load a specified MedGemma VLM model (processor and model) based on its version name. This function will be called within the Gradio interface as needed.

**Reasoning**:
To fulfill the subtask, I will define a Python function `load_medgemma_model` that encapsulates the logic for logging into Hugging Face, loading the specified MedGemma VLM processor and model, and handling potential errors during the loading process.
"""

from transformers import AutoProcessor, AutoModelForCausalLM
from huggingface_hub import login
import torch

def load_medgemma_model(model_name: str):
    """
    Loads a specified MedGemma VLM model and its processor, and handles Hugging Face login.

    Args:
        model_name (str): The name of the MedGemma model to load (e.g., 'google/medgemma-4b-it').

    Returns:
        tuple: A tuple containing the processor and the model, or (None, None) if loading fails.
    """
    print(f"Attempting to load model: {model_name}")
    # Securely log in to Hugging Face Hub
    # Assuming the token is available as a global variable or managed securely
    global token # Access the token from the global scope
    if 'token' in globals() and token:
        try:
            login(token=token)
            print("Hugging Face login successful.")
        except Exception as e:
            print(f"Hugging Face login failed: {e}. Model loading might proceed if already logged in or model is public.")
    else:
        print("Hugging Face token not found or not set. Proceeding without explicit login. This might fail for private models.")

    processor = None
    model = None
    try:
        print(f"Loading processor for {model_name}...")
        processor = AutoProcessor.from_pretrained(model_name)
        print("Processor loaded successfully.")

        print(f"Loading model for {model_name}...")
        # Use device_map='auto' for automatic device placement (GPU if available, otherwise CPU or offloaded)
        model = AutoModelForCausalLM.from_pretrained(model_name, device_map="auto")
        print("Model loaded successfully.")

        if torch.cuda.is_available():
            print("CUDA is available. Model loaded with automatic device mapping.")
        else:
            print("CUDA not available. Model is running on CPU or distributed across CPU/disk.")

        return processor, model

    except Exception as e:
        print(f"Error loading MedGemma model '{model_name}': {e}")
        return None, None

