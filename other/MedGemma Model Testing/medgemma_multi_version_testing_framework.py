"""## Create Gradio Interface for Testing

### Subtask:
Design and implement a Gradio interface that allows users to: 1. Select from the identified MedGemma VLM versions. 2. Upload a medical image. 3. Input a text prompt. 4. Trigger the VLM to generate a response. 5. Display the VLM's generated text response.

**Reasoning**:
I will implement the `predict_function` as described in the instructions, which will handle model loading, input preparation, inference, and decoding. This function will then be used as the core logic for the Gradio interface.
"""

import gradio as gr
from PIL import Image
import torch

# Global variables for caching loaded models and processors
loaded_model = None
loaded_processor = None
current_model_name = ""

def predict_function(model_version, image, text_prompt):
    global loaded_model, loaded_processor, current_model_name

    # 3. Inside predict_function, call the load_medgemma_model function
    # Only load if the model_version has changed or if it's the first run
    if model_version != current_model_name or loaded_model is None or loaded_processor is None:
        print(f"Loading new model version: {model_version}")
        processor, model = load_medgemma_model(model_version)
        if model is None or processor is None:
            # 4. Handle cases where the model or processor fail to load
            return "Error: Failed to load the specified MedGemma VLM model. Please check the model version and your Hugging Face token."
        loaded_processor = processor
        loaded_model = model
        current_model_name = model_version
        print(f"Model '{model_version}' loaded and cached.")
    else:
        print(f"Using cached model: {model_version}")

    # Ensure the model and processor are not None after caching check
    if loaded_model is None or loaded_processor is None:
        return "Error: Model or processor not initialized. This should not happen after successful loading."

    # Get the actual image token ID from the model's config
    image_token_id = loaded_model.config.image_token_id
    if image_token_id is None:
        return "Error: Model config does not define 'image_token_id'. Cannot proceed."

    # Get the number of image tokens the model expects
    num_image_tokens = getattr(loaded_model.config, 'num_image_tokens', 256) # Fallback to 256 if not found in config

    # Define the device
    device = next(loaded_model.parameters()).device # Get the device of the model

    # 5. Prepare the input_ids
    text_input_ids = loaded_processor.tokenizer.encode(text_prompt, add_special_tokens=False)

    input_ids_list = [
        loaded_processor.tokenizer.bos_token_id
    ] + [image_token_id] * num_image_tokens + text_input_ids + [
        loaded_processor.tokenizer.eos_token_id
    ]
    input_ids = torch.tensor([input_ids_list], dtype=torch.long, device=device)

    # 6. Convert the input image to 'RGB' and process it into pixel_values
    if image.mode != 'RGB':
        image = image.convert('RGB')

    pixel_values = loaded_processor.image_processor(image, return_tensors="pt").pixel_values.to(device)

    inputs = {
        "input_ids": input_ids,
        "pixel_values": pixel_values
    }

    print("Generating response...")
    # 8. Generate the response using model.generate
    generated_ids = loaded_model.generate(**inputs, max_new_tokens=200, do_sample=False)
    print("Response generated.")

    # 9. Decode the generated_ids
    generated_text = loaded_processor.batch_decode(generated_ids, skip_special_tokens=True)[0]

    # The generated text might include the prompt itself, so we can try to remove it for cleaner output
    if generated_text.startswith(text_prompt):
        generated_text = generated_text[len(text_prompt):].strip()

    # 10. Return the generated text
    return generated_text

# 11. Create a Gradio Interface
# Assuming `found_versions` is available from previous steps
if 'found_versions' not in globals() or not found_versions:
    found_versions = ['google/medgemma-4b-it'] # Fallback if versions not found
